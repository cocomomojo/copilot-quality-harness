/**
 * Post Copilot Analysis as Comment on Pull Request
 *
 * Input:  ./trace-artifacts/analysis.json
 * Output: Comment on GitHub PR
 *
 * Handles both:
 * - Manual workflow_dispatch (creates Draft PR)
 * - Auto pull_request (posts comment on PR)
 */

import { readFileSync } from "fs";

interface Solution {
  id: number;
  title: string;
  purpose: string;
  patch: string;
  risk: string;
  verify_steps: string[];
  priority: "high" | "medium" | "low";
}

interface Analysis {
  status: string;
  summary: string;
  repro_steps: string[];
  solutions: Solution[];
  metadata: {
    failure_category: string;
    failing_test: string;
    generated_at: string;
  };
}

async function postPRComment() {
  try {
    // Get GitHub environment
    const eventName = process.env.GITHUB_EVENT_NAME || "workflow_dispatch";
    const prNumber = process.env.PR_NUMBER || 
                    process.env.GITHUB_REF?.split("/")[2];
    const repo = process.env.GITHUB_REPOSITORY || "";

    console.log(`📝 Posting comment for ${eventName} event`);
    console.log(`PR Number: ${prNumber}, Repo: ${repo}`);

    // Skip if not a pull_request event and no PR number provided
    if (eventName !== "pull_request" && !prNumber) {
      console.log("⚠️ Not a pull_request event and no PR_NUMBER provided");
      console.log("Skipping comment posting (Draft PR only mode)");
      return;
    }

    // Load analysis
    const analysisPath = "./trace-artifacts/analysis.json";
    const analysisContent = readFileSync(analysisPath, "utf-8");
    const analysis: Analysis = JSON.parse(analysisContent);

    if (analysis.status !== "success") {
      console.error("❌ Analysis status is not success:", analysis.status);
      process.exit(1);
    }

    // Generate comment body
    const commentBody = generateCommentBody(analysis);

    // Use GitHub CLI to post comment
    const { execSync } = require("child_process");
    const ghCommand = `gh pr comment ${prNumber} --body "${commentBody.replace(/"/g, '\\"')}"`;

    console.log("📤 Posting comment via GitHub CLI...");
    const output = execSync(ghCommand, { encoding: "utf-8" });
    console.log("✅ Comment posted successfully");
    console.log(output);
  } catch (error) {
    console.error("❌ Error posting PR comment:", error);
    // Do not exit with error; allow workflow to continue
    // (Draft PR was already created)
  }
}

function generateCommentBody(analysis: Analysis): string {
  const priorityEmoji = {
    high: "🔴",
    medium: "🟡",
    low: "🟢"
  };

  const solutionsSummary = analysis.solutions
    .slice(0, 3)
    .map(
      (sol, idx) => `
**${priorityEmoji[sol.priority]} ${idx + 1}. ${sol.title}**
- Purpose: ${sol.purpose}
- Risk: ${sol.risk}
`
    )
    .join("\n");

  return `## 🤖 Copilot Trace Analysis

**Test Failure**: \`${analysis.metadata.failing_test}\`
**Category**: \`${analysis.metadata.failure_category}\`

### 📋 Summary
${analysis.summary}

### 🔄 How to Reproduce
${analysis.repro_steps.map((step) => `1. ${step}`).join("\n")}

### 💡 Suggested Fixes
${solutionsSummary}

---

### 📌 Next Steps
1. Review the analysis above
2. Choose a fix strategy
3. Implement locally and test
4. Commit and push for CI verification

💬 For detailed fix proposals with code patches, see the **Draft PR** created alongside this comment.

---
*Analysis generated by Copilot on ${analysis.metadata.generated_at}*  
*Label: \`copilot-suggestion\`*`;
}

// Main execution
postPRComment();
